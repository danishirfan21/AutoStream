"""Generate self-contained Power Query scripts, one per workbook table, into queries/bundled/.

Each bundled script inlines every query it depends on as a step of one `let`, so the workbook needs SIX queries
instead of twenty. DataFolder and SyntheticFixtureMode are read from the workbook's tblConfig table (Config sheet)
instead of being hardcoded. The source of truth stays queries/*.pq; re-run this tool after editing them.

Usage: python tools/make_bundles.py
NOT verified in Excel: the generated M has never been executed (no Power Query engine on the build machine).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

Q = Path(__file__).resolve().parents[1] / "queries"
OUT = Q / "bundled"
OUTPUTS = {  # bundled query name -> source query
    "qSourceRecords": "SourceRecords",
    "qLatest": "VinSourceLatest",
    "qFindings": "Findings",
    "qChecks": "Checks",
    "qRuns": "IngestionRuns",
    "qVehicles": "Vehicles",
}
CONFIG = {
    "DataFolder": ('let ov = Config{[Setting = "DataFolderOverride"]}[Value] in '
                   'if ov = null or Text.Trim(Text.From(ov)) = "" then Text.From(Config{[Setting = "DataFolderDefault"]}[Value]) '
                   'else Text.From(ov)'),
    "SyntheticFixtureMode": 'Text.Lower(Text.From(Config{[Setting = "SyntheticFixtureMode"]}[Value])) = "true"',
}


def strip_comments(text: str) -> str:
    return "\n".join(ln for ln in text.splitlines() if not ln.strip().startswith("//"))


def main() -> int:
    bodies = {p.stem: strip_comments(p.read_text(encoding="utf-8")).strip() for p in Q.glob("*.pq")}
    names = set(bodies)
    deps = {n: {m for m in names if m != n and re.search(rf"(?<![\[\.\w]){m}(?!\w)(?!\s*=[^=])", re.sub(r'"[^"]*"', '""', b))}
            for n, b in bodies.items()}

    def closure(root: str) -> list[str]:
        order: list[str] = []
        state: dict[str, int] = {}

        def visit(n: str) -> None:
            if state.get(n) == 2:
                return
            if state.get(n) == 1:
                raise SystemExit(f"dependency cycle at {n}")
            state[n] = 1
            for d in sorted(deps[n] - set(CONFIG)):
                visit(d)
            state[n] = 2
            order.append(n)

        visit(root)
        return order

    OUT.mkdir(exist_ok=True)
    for q, root in OUTPUTS.items():
        steps = ['Config = Excel.CurrentWorkbook(){[Name = "tblConfig"]}[Content]']
        used = closure(root)
        for p in CONFIG:
            if any(p in deps[n] for n in used) or p in deps[root]:
                steps.append(f"{p} = {CONFIG[p]}")
        for n in used:
            if n in CONFIG:
                continue
            steps.append(f"{n} = (\n{bodies[n]}\n)")
        text = (f"// {q}: generated by tools/make_bundles.py from queries/{root}.pq and its dependencies. Do not edit by hand.\n"
                "// Reads DataFolder and SyntheticFixtureMode from tblConfig (Config sheet).\nlet\n"
                + ",\n".join(steps) + f"\nin\n    {root}\n")
        (OUT / f"{q}.pq").write_text(text, encoding="utf-8", newline="\n")
        print(f"{q}.pq  ({len(used)} inlined queries, {len(text):,} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
